};

// Make a 1-cycle start pulse from CONTROL bit0
reg  start_q;
wire start_level = slv_reg0[0];
wire start_pulse = start_level & ~start_q;

always @(posedge S_AXI_ACLK) begin
  if (!S_AXI_ARESETN) start_q <= 1'b0;
  else                start_q <= start_level;
end

